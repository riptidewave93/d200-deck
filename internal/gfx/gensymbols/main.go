// gensymbols writes symbols.go from the rounded, filled icons of a Material
// Symbols release (the @material-symbols/svg-400 npm package):
//
//	go run ./internal/gfx/gensymbols <package>/rounded 0.47.6 > internal/gfx/symbols.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	pathRE    = regexp.MustCompile(`<path d="([^"]+)"`)
	viewBoxRE = regexp.MustCompile(`viewBox="0 -960 960 960"`)
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: gensymbols <rounded dir> <version>")
	}
	dir, version := os.Args[1], os.Args[2]
	files, err := filepath.Glob(filepath.Join(dir, "*-fill.svg"))
	if err != nil || len(files) == 0 {
		log.Fatalf("no *-fill.svg in %s", dir)
	}
	sort.Strings(files)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gensymbols from Material Symbols (Rounded, filled, 400) %s; DO NOT EDIT.\n", version)
	b.WriteString("// Material Symbols are Copyright Google LLC, Apache License 2.0.\n\npackage gfx\n\n")
	b.WriteString("// symbols are the Material Symbols icons by name, sorted, as SVG path data in\n// the viewBox 0 -960 960 960.\n")
	b.WriteString("var symbols = [...]symbol{\n")
	for _, f := range files {
		svg, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		paths := pathRE.FindAllSubmatch(svg, -1)
		if len(paths) != 1 || !viewBoxRE.Match(svg) {
			log.Fatalf("%s: want one path in viewBox 0 -960 960 960", f)
		}
		name := strings.TrimSuffix(filepath.Base(f), "-fill.svg")
		fmt.Fprintf(&b, "{%s, %s},\n", strconv.Quote(name), strconv.Quote(string(paths[0][1])))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	os.Stdout.Write(src)
}
