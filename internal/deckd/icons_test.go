package deckd

import (
	"fmt"
	"maps"
	"os"
	"slices"
	"strings"
	"testing"

	"github.com/riptidewave93/d200-deck/deck"
	"github.com/riptidewave93/d200-deck/icons"
	"github.com/riptidewave93/d200-deck/internal/ota"
)

// TestSystemIcons checks system_icons.go has the icons deckd's own screens
// use, from the catalog; UPDATE_ICONS=1 writes it.
func TestSystemIcons(t *testing.T) {
	want := map[string]deck.Icon{}
	for _, o := range []*overlay{
		confirmScreen(ota.ConfirmRequest{}, nil), progressScreen(ota.StepFailed, "", 0, 0),
		progressScreen("Updating", "", 0, 1), askScreen("", "", "", nil),
	} {
		for _, b := range o.keys {
			if b.Icon != "" {
				ic, ok := icons.Get(b.Icon)
				if !ok {
					t.Fatalf("no icon %q", b.Icon)
				}
				want[b.Icon] = ic
			}
		}
	}
	if maps.Equal(want, systemIcons) {
		return
	}
	if os.Getenv("UPDATE_ICONS") == "" {
		t.Fatal("system_icons.go is out of date: run the deckd tests with UPDATE_ICONS=1")
	}
	var b strings.Builder
	b.WriteString("// Code generated by TestSystemIcons (UPDATE_ICONS=1); DO NOT EDIT.\n// Material Symbols are Copyright Google LLC, Apache License 2.0.\n\npackage deckd\n\nimport \"github.com/riptidewave93/d200-deck/deck\"\n\n// systemIcons are the icons of deckd's own screens.\nvar systemIcons = map[string]deck.Icon{\n")
	for _, n := range slices.Sorted(maps.Keys(want)) {
		fmt.Fprintf(&b, "\t%q: {D: %q, ViewBox: %q},\n", n, want[n].D, want[n].ViewBox)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("system_icons.go", []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}
