// TestDefaultIcons checks default_icons.go has what the default config
// needs from the catalog; UPDATE_ICONS=1 writes it.
func TestDefaultIcons(t *testing.T) {
	c := deck.DefaultConfig()
	got := c.Icons
	if u := icons.Embed(c); len(u) > 0 {
		t.Fatalf("not in the catalog: %q", u)
	}
	if maps.Equal(got, c.Icons) {
		return
	}
	if os.Getenv("UPDATE_ICONS") == "" {
		t.Fatal("default_icons.go is out of date: run the deck tests with UPDATE_ICONS=1")
	}
	var b strings.Builder
	b.WriteString("// Code generated by TestDefaultIcons (UPDATE_ICONS=1); DO NOT EDIT.\n// Material Symbols are Copyright Google LLC, Apache License 2.0.\n\npackage deck\n\n// defaultIcons are DefaultConfig's icons.\nvar defaultIcons = map[string]Icon{\n")
	for _, n := range slices.Sorted(maps.Keys(c.Icons)) {
		ic := c.Icons[n]
		fmt.Fprintf(&b, "\t%q: {D: %q, ViewBox: %q},\n", n, ic.D, ic.ViewBox)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("default_icons.go", []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestIconsValidated(t *testing.T) {
	c := deck.DefaultConfig()
	if err := c.Validate(); err != nil {
		t.Fatal(err)
	}
	if err := c.CheckIcons(); err != nil {
		t.Fatal(err)
	}
	for name, ic := range map[string]deck.Icon{
		"bad path":   {D: "M0", ViewBox: "0 0 1 1"},
		"no viewBox": {D: "M0 0H1V1Z"},
		"empty":      {},
		"both":       {D: "M0 0H1V1Z", ViewBox: "0 0 1 1", PNG: "AAAA"},
		"bad png":    {PNG: "AAAA"},
		"long":       {D: "M0 0" + strings.Repeat(" 1 1", deck.MaxIconPath), ViewBox: "0 0 1 1"},
	} {
		c := deck.DefaultConfig()
		c.Icons["x"] = ic
		if err := c.Validate(); err == nil {
			t.Errorf("%s: valid", name)
		}
	}
	c = deck.DefaultConfig()
	delete(c.Icons, "discord")
	if err := c.Validate(); err != nil {
		t.Errorf("a missing icon failed Validate: %v", err)
	}
	if err := c.CheckIcons(); err == nil {
		t.Error("a missing icon passed CheckIcons")
	}
}
